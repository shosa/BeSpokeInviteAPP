// Messaggi con una parte variabile: l'espressione cattura la parte che resta uguale nelle due lingue.
const PATTERNS: [RegExp, (...m: string[]) => string][] = [
  [/^Manca una risposta: (.+)$/s, (q) => `An answer is missing: ${q}`],
  [/^Campo non valido: (.+)$/, (k) => `Invalid field: ${k}`],
  [/^Numero non valido: (.+)$/, (k) => `Invalid number: ${k}`],
  [/^Valore non valido: (.+)$/, (k) => `Invalid value: ${k}`],
  [/^Data non valida: (.+)$/, (k) => `Invalid date: ${k}`],
  [/^Riferimento non valido: (.+)$/, (k) => `Invalid reference: ${k}`],
  [/^Valore non ammesso: (.+)$/, (k) => `Value not allowed: ${k}`],
  [/^Durata troppo lunga \(massimo (\d+) secondi\)$/, (n) => `Too long (up to ${n} seconds)`],
  [/^File troppo grande \(massimo (\d+) MB\)$/, (n) => `File too large (up to ${n} MB)`],
  [/^Il file convertito è troppo grande \(massimo (\d+) MB\): usane uno più corto o più leggero$/, (n) => `The converted file is too large (up to ${n} MB): use a shorter or lighter one`],
  [/^Il tema è usato da (\d+) invit[oi]: disattivalo invece di eliminarlo$/, (n) => `The style is used by ${n} ${n === "1" ? "invitation" : "invitations"}: disable it instead of deleting it`],
  [/^Esiste già un tema con id "(.+)"$/, (id) => `A style with id "${id}" already exists`],
  [/^Percorso non valido: (.+)$/, (p) => `Invalid path: ${p}`],
  [/^theme\.json non è JSON valido \((.+)\)$/s, (e) => `theme.json is not valid JSON (${e})`],
  [/^Il campo (\S+) non è valido$/, (k) => `The ${k} field is not valid`],
  [/^Il campo (\S+) è troppo lungo \(massimo (\d+) caratteri\)$/, (k, n) => `The ${k} field is too long (up to ${n} characters)`],
  [/^Shopify non risponde correttamente: (.+)$/s, (e) => `Shopify isn't responding correctly: ${e}`],
];

export function errorToEnglish(message: string): string {
  const exact = EXACT[message];
  if (exact) return exact;
  for (const [re, make] of PATTERNS) {
    const m = re.exec(message);
    if (m) return make(...m.slice(1));
  }
  return message;
}
